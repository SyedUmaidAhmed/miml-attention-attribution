"""Generate the instance-attribution tables/figures from result JSONs.

Every number in the new journal paper comes from here. Nothing is hand-typed —
the rejected submissions contained a figure rendered from synthetic placeholder
data and two hardcoded coordinates that disagreed with the JSONs by up to 1.1 AP
points, so generation is mandatory, not a convenience.

Outputs (default --outdir paper_pr/tables_attr/):
    attribution_main.tex   per-dataset method × {bag AP, InstP@1, Δchance, InstAUC}
    attribution_regimes.tex  the witness-structure decomposition per dataset
    attribution_summary.json machine-readable roll-up incl. Spearman correlations

Usage:
    python3 analysis/make_attribution_tables.py
    python3 analysis/make_attribution_tables.py --outdir /tmp/t
"""

from __future__ import annotations

import argparse
import glob
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

RESULTS = 'results/instance_level'

# Methods whose attention is one distribution broadcast across all labels.
# Verified by reading the forward() of each: attnmil.py / gated_attn.py /
# transmil_lite.py all do attn.unsqueeze(1).expand(-1, L, -1).
LABEL_AGNOSTIC = {'attnmil', 'gated_attn', 'transmil_lite'}

DISPLAY = {
    'attnmil': 'AttnMIL~\\cite{ilse2018attention}',
    'gated_attn': 'GatedAttention~\\cite{ilse2018attention}',
    'transmil_lite': 'TransMIL~\\cite{shao2021transmil}',
    'dsmil': 'DSMIL~\\cite{li2021dsmil}',
    'ml_decoder': 'ML-Decoder~\\cite{ridnik2023mldecoder}',
    'q2l': 'Q2L~\\cite{liu2021q2l}',
    'hap_only': 'HAP (ours)',
}
ORDER = ['attnmil', 'gated_attn', 'transmil_lite',
         'dsmil', 'ml_decoder', 'q2l', 'hap_only']
DS_DISPLAY = {
    'letter_frost': 'Letter Frost', 'letter_carroll': 'Letter Carroll',
    'mscv2': 'MSRC~v2', 'voc2012seg': 'VOC-Patch-Seg',
    'voc2012segml': 'VOC-Patch-Seg-ML',
}
DS_ORDER = ['letter_frost', 'letter_carroll', 'mscv2',
            'voc2012seg', 'voc2012segml']


def load_cells():
    out = {}
    for f in glob.glob(os.path.join(RESULTS, '*__*.json')):
        d = json.load(open(f))
        out[(d['method'], d['dataset'])] = d
    return out


DATASET_CEILING = {}   # filled by regime_table(); dataset-level, not fold-level


def main_table(cells, datasets, methods):
    # Emitted as two stacked panels (classical benchmarks / VOC-Patch) so the
    # table fits \textwidth at \footnotesize without \resizebox -- a single
    # 21-column tabular shrinks to unreadable print in the double-spaced
    # elsarticle manuscript.
    if len(datasets) > 3:
        return (_panel(cells, datasets[:3], methods)
                + '\n\\par\\vspace{0.9em}\n'
                + _panel(cells, datasets[3:], methods, header_comment=False))
    return _panel(cells, datasets, methods)


def _panel(cells, datasets, methods, header_comment=True):
    lines = []
    if header_comment:
        lines.append('% GENERATED by analysis/make_attribution_tables.py'
                     ' -- do not edit')
    lines += [
        '\\begin{tabular}{l' + 'cccc' * len(datasets) + '}',
        '\\toprule',
    ]
    hdr = ['Method']
    for ds in datasets:
        hdr.append('\\multicolumn{4}{c}{' + DS_DISPLAY.get(ds, ds) + '}')
    lines.append(' & '.join(hdr) + ' \\\\')
    sub = ['']
    for _ in datasets:
        sub += ['AP', 'P@1', '$\\Delta$', 'AUC']
    lines.append(' & '.join(sub) + ' \\\\')
    lines.append('\\midrule')

    for m in methods:
        row = [DISPLAY.get(m, m)]
        for ds in datasets:
            d = cells.get((m, ds))
            if d is None:
                row += ['--'] * 4
                continue
            im = d['instance_metrics_mean_std']
            ap = d['bag_metrics_mean_std']['AveragePrecision'][0]
            p1 = im['InstP@1'][0]
            ch = im['ChanceP@1'][0]
            auc = im['InstAUC'][0]
            row += [f'{ap:.3f}', f'{100*p1:.1f}',
                    f'{100*(p1-ch):+.1f}', f'{auc:.3f}']
        lines.append(' & '.join(row) + ' \\\\')
        if m == 'transmil_lite':
            lines.append('\\midrule')

    # reference rows
    ref = ['\\textit{chance}']
    ceil = ['\\textit{ceiling (agnostic)}']
    for ds in datasets:
        anyd = next((cells[(m, ds)] for m in methods if (m, ds) in cells), None)
        if anyd is None:
            ref += ['--'] * 4
            ceil += ['--'] * 4
            continue
        im = anyd['instance_metrics_mean_std']
        # Chance is a test-fold average (it is what the models were scored
        # against). The ceiling is a property of the whole benchmark, so it is
        # taken from DATASET_CEILING to match tab:regimes exactly -- reporting
        # a fold-averaged ceiling here and a dataset ceiling there would put
        # two different numbers for one quantity in the same paper.
        ref += ['--', f'{100*im["ChanceP@1"][0]:.1f}', '--', '0.500']
        dc = DATASET_CEILING.get(ds)
        ceil += ['--', ('--' if dc is None else f'{100*dc:.1f}'), '--', '--']
    lines.append('\\midrule')
    lines.append(' & '.join(ref) + ' \\\\')
    lines.append(' & '.join(ceil) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}']
    return '\n'.join(lines)


KEY_FOR_DISPLAY = {'MSRC~v2': 'mscv2', 'Letter Frost': 'letter_frost',
                   'Letter Carroll': 'letter_carroll',
                   'VOC-Patch-Seg': 'voc2012seg',
                   'VOC-Patch-Seg-ML': 'voc2012segml'}


def regime_table():
    """Witness-structure decomposition — the theorem's precondition per dataset."""
    from miml_clam.metrics.instance_metrics import (
        chance_precision_at_1, label_agnostic_ceiling, witness_disjointness)
    from analysis.instance_level_stats import load_padded

    rows = []
    for name, key in [('MSRC~v2', 'MSCV2'), ('Letter Frost', 'letter_frost'),
                      ('Letter Carroll', 'letter_carroll')]:
        _, inst, bag, mask = load_padded(key)
        rows.append((name, inst, bag, mask))

    # VOC-Patch-Seg from its side-car
    from datasets.voc_miml import DEFAULT_OUT_DIR
    for disp, stem in [('VOC-Patch-Seg', 'voc2012seg'),
                       ('VOC-Patch-Seg-ML', 'voc2012segml')]:
        try:
            z = np.load(os.path.join(DEFAULT_OUT_DIR, f'{stem}_patch_gt.npz'),
                        allow_pickle=True)
            rows.append((disp, z['patch_seg'].astype(bool),
                         z['bag_labels'].astype(bool), None))
        except Exception as exc:                               # pragma: no cover
            sys.stderr.write(f'warning: {stem} not available ({exc})\n')

    out = [
        '% GENERATED by analysis/make_attribution_tables.py -- do not edit',
        '\\begin{tabular}{lrrrrr}',
        '\\toprule',
        'Dataset & Bags & Disjoint pairs & Chance P@1 & Ceiling & Headroom \\\\',
        '\\midrule',
    ]
    summary = {}
    for name, inst, bag, mask in rows:
        ch = chance_precision_at_1(inst, bag, mask)
        ce = label_agnostic_ceiling(inst, bag, mask)
        dj = witness_disjointness(inst, bag, mask)
        out.append(f'{name} & {bag.shape[0]} & {100*dj:.1f}\\% & '
                   f'{100*ch:.1f}\\% & {100*ce:.1f}\\% & '
                   f'{100*(ce-ch):+.1f} pts \\\\')
        summary[name] = {'bags': int(bag.shape[0]), 'disjointness': dj,
                         'chance': ch, 'ceiling': ce, 'headroom': ce - ch}
        DATASET_CEILING[KEY_FOR_DISPLAY[name]] = ce
    out += ['\\bottomrule', '\\end{tabular}']
    return '\n'.join(out), summary


def correlations(cells, datasets):
    """Spearman rho(bag AP, InstP@1) -- what ICDM R3 explicitly asked for."""
    from scipy.stats import spearmanr
    out = {}
    for ds in datasets:
        ms = [m for m in ORDER if (m, ds) in cells]
        cond = [m for m in ms if m not in LABEL_AGNOSTIC]
        for label, sel in [('all_methods', ms), ('label_conditional', cond)]:
            if len(sel) < 3:
                continue
            ap = [cells[(m, ds)]['bag_metrics_mean_std']['AveragePrecision'][0]
                  for m in sel]
            p1 = [cells[(m, ds)]['instance_metrics_mean_std']['InstP@1'][0]
                  for m in sel]
            r, p = spearmanr(ap, p1)
            spread_ap = 100 * (max(ap) - min(ap))
            spread_p1 = 100 * (max(p1) - min(p1))
            # scipy's Spearman p-value is asymptotic and INVALID at these
            # sample sizes: with n=4 the smallest attainable two-sided p is
            # 2/4! = 0.083, yet scipy reports 0.0000 for a perfect ordering,
            # and rho=+1.0 arises by chance in 1 of 24 random orderings.
            # The rank correlation is therefore reported as descriptive only.
            reliable = len(sel) >= 8
            # The defensible statistic is the magnification: a direct
            # comparison of observed ranges, requiring no inference.
            worst = min(zip(p1, sel))[1]
            worst_ap_rank = sorted(sel, key=lambda m: -ap[sel.index(m)]).index(worst) + 1
            out.setdefault(ds, {})[label] = {
                'n': len(sel), 'spearman_rho': float(r),
                'p_value_asymptotic_UNRELIABLE': float(p),
                'rho_is_reliable': reliable,
                'min_attainable_two_sided_p': None if reliable else 2 / math.factorial(len(sel)),
                'bag_ap_spread_pts': spread_ap,
                'inst_p1_spread_pts': spread_p1,
                'magnification': (spread_p1 / spread_ap) if spread_ap else None,
                'worst_attribution_method': worst,
                'its_bag_ap_rank': worst_ap_rank,
            }
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default='paper_pr/tables_attr')
    args = ap.parse_args()
    os.makedirs(args.outdir, exist_ok=True)

    cells = load_cells()
    datasets = [d for d in DS_ORDER if any(k[1] == d for k in cells)]
    methods = [m for m in ORDER if any(k[0] == m for k in cells)]
    if not datasets:
        sys.exit('no result cells found in ' + RESULTS)

    t2, regimes = regime_table()          # must precede main_table: fills DATASET_CEILING
    t1 = main_table(cells, datasets, methods)
    open(os.path.join(args.outdir, 'attribution_main.tex'), 'w').write(t1 + '\n')

    open(os.path.join(args.outdir, 'attribution_regimes.tex'), 'w').write(t2 + '\n')

    corr = correlations(cells, datasets)
    summary = {
        'cells': {f'{m}__{d}': True for (m, d) in cells},
        'datasets': datasets,
        'methods': methods,
        'label_agnostic': sorted(LABEL_AGNOSTIC),
        'regimes': regimes,
        'correlations': corr,
    }
    with open(os.path.join(args.outdir, 'attribution_summary.json'), 'w') as f:
        json.dump(summary, f, indent=2, default=float)

    print(f'wrote 3 files to {args.outdir}')
    print(f'  datasets: {", ".join(datasets)}')
    print(f'  methods : {len(methods)}  cells: {len(cells)}')
    for ds, v in corr.items():
        lc = v.get('label_conditional')
        if lc:
            flag = '' if lc['rho_is_reliable'] else '  [rho descriptive only, n too small]'
            print(f'  {ds:14s} magnification={lc["magnification"]:5.1f}x  '
                  f'(bagAP spread {lc["bag_ap_spread_pts"]:.1f}pts -> '
                  f'attribution spread {lc["inst_p1_spread_pts"]:.1f}pts); '
                  f'worst attribution = {lc["worst_attribution_method"]} '
                  f'(bag-AP rank {lc["its_bag_ap_rank"]}/{lc["n"]}){flag}')


if __name__ == '__main__':
    main()
