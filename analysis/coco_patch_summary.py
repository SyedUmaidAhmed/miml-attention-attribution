"""COCO-Patch-ML (8x8 grid): dataset regime, per-architecture results, fold-level tests.

Reads the eight cells in results/instance_level_r1_coco (10 folds x 1 model,
seed 42 + fold, batch 8, VOC widths, CPU) and the side-car built by
datasets/build_coco_patch.py (COCO_PATCH_DIR, default ~/data/coco_patch).

    /opt/anaconda3/bin/python3 analysis/coco_patch_summary.py
writes paper_attribution/tables/coco_patch.json and coco_patch.tex

Gates (stop on failure): every cell has 10 models (folds 0..9); no NaN in any
per-model record; every label-agnostic model has P@1 <= its label-agnostic
ceiling (Theorem 1; a violation is a bug).

Tests: fold-level two-sided Nadeau-Bengio corrected t-test on per-fold
differences (one model per fold), Holm over the 28 pairs of architectures,
separately for P@1, pooled attribution AUC and per-model bag AP (as analysis/attribution_stats.py).
"""
import argparse
import itertools
import json
import math
import os

import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from miml_clam.metrics.instance_metrics import (  # noqa: E402
    chance_precision_at_1, label_agnostic_auc_bounds, label_agnostic_ceiling)
from attribution_stats import holm, nb_corrected_t

RESULTS = 'results/instance_level_r1_coco'
DS = 'coco2017val_g8'
# $COCO_PATCH_DIR, else ~/data/coco_patch, else the repository's data/coco_patch
GT = next((p for p in [os.path.join(d, 'coco2017val_g8_patch_gt.npz') for d in
           (os.environ.get('COCO_PATCH_DIR', ''), os.path.expanduser('~/data/coco_patch'),
            'data/coco_patch') if d] if os.path.exists(p)),
          os.path.expanduser('~/data/coco_patch/coco2017val_g8_patch_gt.npz'))
ORDER = ['attnmil', 'gated_attn', 'transmil_lite', 'dsmil_orig', 'dsmil',
         'ml_decoder', 'q2l', 'hap_only']
DISPLAY = {'attnmil': 'AB-MIL', 'gated_attn': 'Gated AB-MIL',
           'transmil_lite': 'TransMIL', 'dsmil_orig': 'DSMIL',
           'dsmil': 'DSMIL-sep', 'ml_decoder': 'ML-Decoder', 'q2l': 'Q2L',
           'hap_only': 'HAP'}
AG = ['attnmil', 'gated_attn', 'transmil_lite']
LC = ['dsmil_orig', 'dsmil', 'ml_decoder', 'q2l', 'hap_only']
HEAD = '% GENERATED by analysis/coco_patch_summary.py -- do not edit'


def dataset_regime():
    z = np.load(GT, allow_pickle=True)
    ps, bl = z['patch_seg'], z['bag_labels']
    lab = bl.sum(1)
    # witness sets of the present labels pairwise disjoint (partition regime)
    disjoint = 0
    for b in range(len(bl)):
        w = ps[b][:, bl[b]]
        disjoint += int((w.sum(1) <= 1).all())
    lo, hi = label_agnostic_auc_bounds(ps, bl)
    present = [(b, l) for b in range(len(bl)) for l in np.flatnonzero(bl[b])]
    nw = np.array([ps[b, :, l].sum() for b, l in present])
    return {'bags': int(len(bl)), 'labels': int(bl.shape[1]),
            'patches_per_bag': int(ps.shape[1]),
            'labels_per_bag': float(lab.mean()),
            'min_labels_per_bag': int(lab.min()), 'max_labels_per_bag': int(lab.max()),
            'witnesses_per_pair_mean': float(nw.mean()),
            'pairs_without_witness': int((nw == 0).sum()),
            'pairs_all_patches_witness': int((nw == ps.shape[1]).sum()),
            'share_bags_disjoint_witnesses': disjoint / len(bl),
            'dataset_chance': float(chance_precision_at_1(ps, bl)),
            'dataset_ceiling': float(label_agnostic_ceiling(ps, bl)),
            'dataset_gamma_auc': [float(lo), float(hi)],
            'threshold': float(z['threshold']), 'grid': int(z['grid']),
            'build_stats': json.loads(str(z['stats_json']))}


def load():
    cells = {}
    for m in ORDER:
        f = os.path.join(RESULTS, f'{m}__{DS}.json')
        if os.path.exists(f):
            cells[m] = json.load(open(f))
    return cells


def gates(cells):
    bad = []
    for m, d in cells.items():
        pm = d['instance_per_model']
        if sorted(r['fold'] for r in pm) != list(range(10)):
            bad.append(f'{m}: folds {sorted(r["fold"] for r in pm)}')
        for r in pm:
            for k, v in r.items():
                if isinstance(v, float) and math.isnan(v):
                    bad.append(f'{m} fold {r["fold"]}: NaN in {k}')
            if m in AG and r['InstP@1'] > r['LabelAgnosticCeiling'] + 1e-9:
                bad.append(f'{m} fold {r["fold"]}: P@1 {r["InstP@1"]:.4f} > Gamma {r["LabelAgnosticCeiling"]:.4f}')
    if bad:
        raise SystemExit('GATE FAILED:\n' + '\n'.join(bad))


def per_fold(d, k):
    return {r['fold']: r[k] for r in d['instance_per_model']}


def summarise(d, m):
    pm = d['instance_per_model']
    g = lambda k: np.array([r[k] for r in pm], float)  # noqa: E731
    out = {}
    for k in ['InstP@1', 'ChanceP@1', 'LabelAgnosticCeiling', 'InstAUC', 'InstAUCPooled', 'AddAUCPooled',
              'InstMRR', 'BagAveragePrecision', 'BagMacroF1', 'BagMicroF1',
              'AddP@1', 'DelTopSelective', 'DelRndSelective']:
        if all(k in r for r in pm):
            v = g(k)
            out[k] = [float(v.mean()), float(v.std(ddof=1))]
    margin = g('InstP@1') - g('ChanceP@1')
    out['margin'] = [float(margin.mean()), float(margin.std(ddof=1))]
    out['n_models'] = len(pm)
    out['max_P1_minus_Gamma'] = float((g('InstP@1') - g('LabelAgnosticCeiling')).max())
    out['class'] = 'label-agnostic' if m in AG else 'label-conditional'
    return out


def tests(cells, metric):
    ms = [m for m in ORDER if m in cells]
    rows = []
    for a, b in itertools.combinations(ms, 2):
        fa, fb = per_fold(cells[a], metric), per_fold(cells[b], metric)
        folds = sorted(set(fa) & set(fb))
        diff = [fa[f] - fb[f] for f in folds]
        t, p = nb_corrected_t(diff)
        rows.append({'a': a, 'b': b, 'mean_diff': float(np.mean(diff)),
                     'folds_same_sign': int(sum(np.sign(x) == np.sign(np.mean(diff)) for x in diff)),
                     't': t, 'p': p})
    adj = holm(np.array([r['p'] for r in rows])) if rows else []
    for r, q in zip(rows, adj):
        r['p_holm'] = float(q)
        r['significant'] = bool(q < 0.05)
    return rows


def f(x, nd=1, sign=False):
    s = f'{100 * x:+.{nd}f}' if sign else f'{100 * x:.{nd}f}'
    return s.replace('-', '$-$', 1)


def table(summ, regime):
    lines = [HEAD, '\\begin{tabular}{@{}lccccc@{}}', '\\toprule',
             'Architecture & AP & P@1 & $\\Delta$ & AUC$_{\\mathrm{pool}}$ & Additive P@1 \\\\',
             '\\midrule']
    for cls, ms in (('Label-agnostic', AG), ('Label-conditional', LC)):
        lines.append(f'\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{cls}}}}} \\\\')
        for m in ms:
            s = summ.get(m)
            if s is None:
                lines.append(f'{DISPLAY[m]} & -- & -- & -- & -- & -- \\\\')
                continue
            add = f(s['AddP@1'][0]) if m in AG and 'AddP@1' in s else '--'
            lines.append(f'{DISPLAY[m]} & {s["BagAveragePrecision"][0]:.3f} & '
                         f'{f(s["InstP@1"][0])} & {f(s["margin"][0], sign=True)} & '
                         f'{s["InstAUCPooled"][0]:.3f} & {add} \\\\')
    any_s = next(iter(summ.values()))
    lines += ['\\midrule',
              f'\\multicolumn{{6}}{{@{{}}l}}{{Chance {f(any_s["ChanceP@1"][0])}, '
              f'label-agnostic ceiling $\\Gamma$ {f(any_s["LabelAgnosticCeiling"][0])} '
              f'(fold averages); $\\Gamma_{{\\mathrm{{AUC}}}}$ {regime["dataset_gamma_auc"][1]:.3f} (whole dataset)}} \\\\',
              '\\bottomrule', '\\end{tabular}']
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default='paper_attribution/tables')
    a = ap.parse_args()
    cells = load()
    gates(cells)
    summ = {m: summarise(cells[m], m) for m in ORDER if m in cells}
    regime = dataset_regime()
    out = {'dataset': DS, 'protocol': '10 folds x 1 model (seed 42+fold), batch 8, '
           'embed 128 / ff 256 / attn 64, CPU', 'cells_complete': len(cells),
           'regime': regime, 'per_method': summ,
           'tests_P1': tests(cells, 'InstP@1'),
           'tests_BagAP': tests(cells, 'BagAveragePrecision'),
           'tests_AUC': tests(cells, 'InstAUCPooled')}
    json.dump(out, open(os.path.join(a.outdir, 'coco_patch.json'), 'w'), indent=1)
    open(os.path.join(a.outdir, 'coco_patch.tex'), 'w').write(table(summ, regime))
    print(f'{len(cells)}/8 cells; gates passed')
    for m, s in summ.items():
        print(f'{DISPLAY[m]:13s} AP {100*s["BagAveragePrecision"][0]:5.1f}  P@1 {100*s["InstP@1"][0]:5.1f}'
              f'  margin {100*s["margin"][0]:+5.1f}  AUCpool {100*s["InstAUCPooled"][0]:5.1f}')


if __name__ == '__main__':
    main()
