"""Generate the experimental-setup tables for the attribution paper.

Added after the Neurocomputing desk rejection (NEUCOM-D-26-19802, 2026-09-04),
whose stated reason was that the experimental methodology -- architecture
adaptations, training protocol, attention extraction, hyper-parameters,
statistical methodology, metric definitions -- was unspecified in the text.
Every number in the new Architectures / Experimental Setup sections is emitted
here from the same sources the results come from, so the setup tables cannot
drift from the runs the way a hand-typed table could.

Outputs (default --outdir paper_attribution/tables/):
    dataset_stats.tex      per-benchmark size / label / witness statistics
    hyperparams.tex        the training configuration actually stored in the
                           result JSONs (classical vs VOC-Patch columns)
    param_counts.tex       trainable-parameter counts of the seven models,
                           instantiated with the stored configs
    attribution_stats.tex  every Holm-corrected pairwise test on P@1

Usage:
    python3 analysis/make_setup_tables.py
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

RESULTS = 'results/instance_level'

DISPLAY = {
    'attnmil': 'AB-MIL', 'gated_attn': 'Gated AB-MIL', 'transmil_lite': 'TransMIL',
    'dsmil': 'DSMIL', 'ml_decoder': 'ML-Decoder', 'q2l': 'Q2L', 'hap_only': 'HAP',
}
ORDER = ['attnmil', 'gated_attn', 'transmil_lite',
         'dsmil', 'ml_decoder', 'q2l', 'hap_only']
DS_DISPLAY = {
    'letter_frost': 'Letter Frost', 'letter_carroll': 'Letter Carroll',
    'mscv2': 'MSRC~v2', 'voc2012seg': 'VOC-Patch-Seg',
    'voc2012segml': 'VOC-Patch-Seg-ML',
}
DS_ORDER = ['letter_frost', 'letter_carroll', 'mscv2', 'voc2012seg',
            'voc2012segml']
CLASSICAL = DS_ORDER[:3]


def load_cells():
    out = {}
    for f in glob.glob(os.path.join(RESULTS, '*__*.json')):
        d = json.load(open(f))
        out[(d['method'], d['dataset'])] = d
    return out


# --------------------------------------------------------------------------
# 1. dataset statistics
# --------------------------------------------------------------------------
def dataset_table(cells):
    from miml_clam.metrics.instance_metrics import check_or_consistency
    from analysis.instance_level_stats import load_padded
    from datasets.voc_miml import DEFAULT_OUT_DIR

    rows = []
    for ds in DS_ORDER:
        if ds in CLASSICAL:
            key = {'mscv2': 'MSCV2'}.get(ds, ds)
            _, inst, bag, mask = load_padded(key)
            valid = ~mask
            n_inst = int(valid.sum())
            inst_per_bag = valid.sum(1)
        else:
            z = np.load(os.path.join(DEFAULT_OUT_DIR, f'{ds}_patch_gt.npz'),
                        allow_pickle=True)
            inst = z['patch_seg'].astype(bool)
            bag = z['bag_labels'].astype(bool)
            mask = None
            n_inst = inst.shape[0] * inst.shape[1]
            inst_per_bag = np.full(inst.shape[0], inst.shape[1])
        cfg = next(cells[(m, ds)]['config'] for m in ORDER if (m, ds) in cells)
        frac, uncovered = check_or_consistency(inst, bag, mask)
        # witnesses per bag: instances carrying >=1 label
        wit = inst.any(axis=2)
        if mask is not None:
            wit &= ~mask
        rows.append({
            'name': DS_DISPLAY[ds], 'bags': bag.shape[0], 'instances': n_inst,
            'labels': bag.shape[1], 'dim': cfg['input_dim'],
            'inst_per_bag': float(inst_per_bag.mean()),
            'labels_per_bag': float(bag.sum(1).mean()),
            'multi': 100 * float((bag.sum(1) > 1).mean()),
            'witness_frac': 100 * float(wit.sum() / n_inst),
            'uncovered': int(uncovered), 'bag_labels': int(bag.sum()),
            'folds': cells[next(m for m in ORDER if (m, ds) in cells), ds]['num_folds'],
        })

    out = ['% GENERATED by analysis/make_setup_tables.py -- do not edit',
           '\\begin{tabular}{lrrrrrrrrr}', '\\toprule',
           'Benchmark & Bags & Inst. & $L$ & $d$ & Inst./bag & Labels/bag & '
           'Multi & Witness & Unwit. \\\\',
           '\\midrule']
    for r in rows:
        out.append(f"{r['name']} & {r['bags']:,} & {r['instances']:,} & "
                   f"{r['labels']} & {r['dim']:,} & {r['inst_per_bag']:.2f} & "
                   f"{r['labels_per_bag']:.2f} & {r['multi']:.1f}\\% & "
                   f"{r['witness_frac']:.1f}\\% & "
                   f"{r['uncovered']}/{r['bag_labels']:,} \\\\")
    out += ['\\bottomrule', '\\end{tabular}']
    return '\n'.join(out), rows


