# 2. hyper-parameters, read from the stored run configs
# --------------------------------------------------------------------------
HP_ROWS = [
    ('Embedding width $D$', 'embed_dim', '{}'),
    ('Embedding MLP layers', 'embedding_layers', '{}'),
    ('Attention width $D\'$ (AB-MIL, gated, DSMIL, HAP)', 'attn_dim', '{}'),
    ('Attention heads (TransMIL, ML-Decoder, Q2L, HAP)', 'nhead', '{}'),
    ('Feed-forward width', 'ff_dim', '{}'),
    ('Encoder layers (TransMIL, HAP)', 'transformer_layers', '{}'),
    ('HAP top-$k$', 'hap_topk', '{}'),
    ('Dropout', 'dropout', '{}'),
    ('Batch size (bags)', 'batch_size', '{}'),
    ('Weight decay', 'weight_decay', '{:g}'),
    ('Gradient-norm clip', 'gradient_clip', '{:g}'),
    ('Label smoothing', 'label_smoothing', '{}'),
    ('Phase-1 epochs', 'phase1_epochs', '{}'),
    ('Phase-1 learning rate', 'phase1_lr', '{:g}'),
    ('Phase-2 maximum epochs', 'phase2_max_epochs', '{}'),
    ('Phase-2 learning rate', 'phase2_lr', '{:g}'),
    ('Early-stopping patience (epochs)', 'early_stop_patience', '{}'),
    ('SWA start epoch (phase 2)', 'swa_start', '{}'),
    ('Phase-2 loss weight', 'bag_weight', '{}'),
]


def hyperparam_table(cells):
    c_cls = cells[('hap_only', 'mscv2')]['config']
    c_voc = cells[('hap_only', 'voc2012seg')]['config']
    # Every cell must match its column's reference config; any exception is
    # emitted as a footnote rather than silently averaged away.
    exceptions = []
    for m in ORDER:
        for ds in DS_ORDER:
            ref = c_cls if ds in CLASSICAL else c_voc
            c = cells[(m, ds)]['config']
            for label, k, fmt in HP_ROWS:
                if c.get(k) != ref.get(k):
                    exceptions.append((label, DISPLAY[m], DS_DISPLAY[ds],
                                       fmt.format(c.get(k))))
    seeds_cls = cells[('hap_only', 'mscv2')]['ensemble_seeds']
    out = ['% GENERATED by analysis/make_setup_tables.py -- do not edit',
           '\\begin{tabular}{lcc}', '\\toprule',
           'Setting & Classical benchmarks & VOC-Patch \\\\', '\\midrule']
    for label, k, fmt in HP_ROWS:
        a = fmt.format(c_cls[k])
        b = fmt.format(c_voc[k])
        out.append(f'{label} & {a} & {b} \\\\')
    out.append(f'Folds & {cells[("hap_only", "mscv2")]["num_folds"]} & '
               f'{cells[("hap_only", "voc2012seg")]["num_folds"]} \\\\')
    out.append(f'Models per fold & {len(seeds_cls)} & 1 \\\\')
    out.append('Seeds & ' + ', '.join(str(s) for s in seeds_cls)
               + ' & $42+f$ for fold $f$ \\\\')
    out.append(f'Models per (method, benchmark) cell & '
               f'{len(cells[("hap_only", "mscv2")]["instance_per_model"])} & '
               f'{len(cells[("hap_only", "voc2012seg")]["instance_per_model"])} \\\\')
    out += ['\\bottomrule', '\\end{tabular}']
    if exceptions:
        notes = '; '.join(f'{lab} is {val} for {m} on {ds}'
                          for lab, m, ds, val in exceptions)
        out.append('\\par\\smallskip\\footnotesize Exception: ' + notes + '.')
    return '\n'.join(out)


# --------------------------------------------------------------------------
# 3. parameter counts
# --------------------------------------------------------------------------
def param_table(cells):
    import torch  # noqa: F401
    from baselines.run_baselines import MODEL_FACTORIES, BASELINE_OVERRIDES
    from miml_clam.training.enhanced_train_cv import create_model
    from run_alfapp_ablation import ROW_OVERRIDES

    def count(m):
        return sum(p.numel() for p in m.parameters() if p.requires_grad)

    cols = ['letter_frost', 'mscv2', 'voc2012seg']   # letter_carroll == letter_frost
    out = ['% GENERATED by analysis/make_setup_tables.py -- do not edit',
           '\\begin{tabular}{l' + 'r' * len(cols) + '}', '\\toprule',
           'Model & ' + ' & '.join(
               {'letter_frost': 'Letter ($d{=}16$, $L{=}26$)',
                'mscv2': 'MSRC~v2 ($d{=}48$, $L{=}23$)',
                'voc2012seg': 'VOC-Patch ($d{=}2048$, $L{=}20$)'}[c]
               for c in cols) + ' \\\\', '\\midrule']
    for m in ORDER:
        row = [DISPLAY[m]]
        for ds in cols:
            cfg = dict(cells[(m, ds)]['config'])
            if m in MODEL_FACTORIES:
                cfg.update(BASELINE_OVERRIDES)
                model = MODEL_FACTORIES[m](cfg, 'cpu')
            else:
                cfg.update({k: v for k, v in ROW_OVERRIDES[m].items()
                            if not k.startswith('_')})
                model = create_model(cfg, 'cpu')
            row.append(f'{count(model):,}')
        out.append(' & '.join(row) + ' \\\\')
        if m == 'transmil_lite':
            out.append('\\midrule')
    out += ['\\bottomrule', '\\end{tabular}']
    return '\n'.join(out)


# --------------------------------------------------------------------------
# 4. statistical tests
# --------------------------------------------------------------------------
def stats_table(stats_path, datasets=CLASSICAL):
    d = json.load(open(stats_path))
    out = ['% GENERATED by analysis/make_setup_tables.py -- do not edit',
           '\\begin{tabular}{llrrrr}', '\\toprule',
           'Benchmark & Comparison & $\\Delta$P@1 & 95\\% CI & '
           '$p_{\\mathrm{Holm}}$ & $\\delta$ \\\\', '\\midrule']
    for ds in datasets:
        r = d['per_dataset'][ds]
        comps = sorted(r['comparisons'], key=lambda c: -abs(c['mean_diff']))
        first = True
        for c in comps:
            a, b = c['a'], c['b']
            if c.get('note'):
                diffstr, ci, cell_p, dstr = '0.0', '---', '---', '0.00'
            else:
                p = c['p_holm']
                cell_p = '$<10^{-3}$' if p < 1e-3 else f'{p:.3f}'
                ci = f"[{100*c['ci'][0]:+.1f}, {100*c['ci'][1]:+.1f}]"
                dstr = f"{c['cliffs_delta']:+.2f}"
                diffstr = f"{100*c['mean_diff']:+.1f}"
            name = DS_DISPLAY[ds] if first else ''
            first = False
            out.append(f'{name} & {DISPLAY[a]} $>$ {DISPLAY[b]} & {diffstr} & '
                       f'{ci} & {cell_p} & {dstr} \\\\')
        out.append('\\midrule')
    out[-1] = '\\bottomrule'
    out.append('\\end{tabular}')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default='paper_attribution/tables')
    ap.add_argument('--stats', default='paper_attribution/tables/attribution_stats.json')
    args = ap.parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    cells = load_cells()

    t, rows = dataset_table(cells)
    open(os.path.join(args.outdir, 'dataset_stats.tex'), 'w').write(t + '\n')
    open(os.path.join(args.outdir, 'hyperparams.tex'), 'w').write(
        hyperparam_table(cells) + '\n')
    open(os.path.join(args.outdir, 'param_counts.tex'), 'w').write(
        param_table(cells) + '\n')
    if os.path.exists(args.stats):
        open(os.path.join(args.outdir, 'attribution_stats.tex'), 'w').write(
            stats_table(args.stats) + '\n')
        # Two panels for the appendix: 63 rows do not fit one page.
        open(os.path.join(args.outdir, 'attribution_stats_a.tex'), 'w').write(
            stats_table(args.stats, CLASSICAL[:2]) + '\n')
        open(os.path.join(args.outdir, 'attribution_stats_b.tex'), 'w').write(
            stats_table(args.stats, CLASSICAL[2:]) + '\n')
    else:
        sys.stderr.write(f'warning: {args.stats} missing; run '
                         'analysis/attribution_stats.py --out <that path>\n')
    json.dump(rows, open(os.path.join(args.outdir, 'dataset_stats.json'), 'w'),
              indent=2)
    print('wrote dataset_stats / hyperparams / param_counts / attribution_stats')
    for r in rows:
        print(f"  {r['name']:18s} bags={r['bags']:5d} inst/bag={r['inst_per_bag']:.2f} "
              f"labels/bag={r['labels_per_bag']:.2f} multi={r['multi']:.1f}% "
              f"witness={r['witness_frac']:.1f}% unwitnessed={r['uncovered']}")


if __name__ == '__main__':
    main()
