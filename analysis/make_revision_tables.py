"""Tables added in the DMKD revision, generated from results/instance_level_r1.

    python3 analysis/make_revision_tables.py --outdir paper_attribution/tables

Writes (every number generated; never hand-edit):
  additive_readout.tex  attention vs additive read-out a_j u_l^T h_j  (R1 pt 2)
  deletion_test.tex     logit drop when the top / a random instance is removed (R1 pt 7, R3 pt 1)
  hap_ablation.tex      HAP mixture and top-k ablation, learned alpha  (R1 pt 6, R3 pt 4)
  bag_f1.tex            per-model Macro-/Micro-F1                     (R2 pt 2)
  ensemble_ap.tex       per-model vs fold-ensemble AP (appendix)      (R1 pt 5)
  revision_summary.json all of the above plus within-architecture
                        Spearman(AP, P@1) over each cell's models    (R1 pt 5)
Cells that have not been run yet print as '--'.
"""

import argparse
import glob
import json
import os

import numpy as np
from scipy.stats import spearmanr

RESULTS = 'results/instance_level_r1'
DISPLAY = {'attnmil': 'AB-MIL', 'gated_attn': 'Gated AB-MIL',
           'transmil_lite': 'TransMIL', 'dsmil_orig': 'DSMIL',
           'dsmil': 'DSMIL-sep', 'ml_decoder': 'ML-Decoder', 'q2l': 'Q2L',
           'hap_only': 'HAP'}
ORDER = ['attnmil', 'gated_attn', 'transmil_lite', 'dsmil_orig', 'dsmil',
         'ml_decoder', 'q2l', 'hap_only']
CLASSICAL = ['letter_frost', 'letter_carroll', 'mscv2', 'hja_birdsong']
VOC = ['voc2012seg_nc', 'voc2012segml_nc']
DS = {'letter_frost': 'Letter Frost', 'letter_carroll': 'Letter Carroll',
      'mscv2': 'MSRC~v2', 'hja_birdsong': 'Bird Song',
      'voc2012seg_nc': 'VOC-Patch-Seg', 'voc2012segml_nc': 'VOC-Patch-Seg-ML'}
HAP_ROWS = [('hap_only', 'learned $\\alpha_l$, $k=3$ (HAP)'),
            ('hap_soft_only', '$\\alpha_l = 1$ (soft only)'),
            ('hap_hard_only', '$\\alpha_l = 0$ (top-$k$ only)'),
            ('hap_k1', 'learned $\\alpha_l$, $k=1$'),
            ('hap_k5', 'learned $\\alpha_l$, $k=5$')]
HEAD = '% GENERATED by analysis/make_revision_tables.py -- do not edit'


def load():
    cells = {}
    for f in glob.glob(os.path.join(RESULTS, '*__*.json')):
        d = json.load(open(f))
        cells[(d['method'], d['dataset'])] = d
    return cells


def mean(d, k):
    v = d['instance_metrics_mean_std'].get(k)
    return None if v is None else v[0]


def fmt(x, nd=3, pct=False, sign=False):
    if x is None:
        return '--'
    x = 100 * x if pct else x
    s = f'{x:+.{nd}f}' if sign else f'{x:.{nd}f}'
    return s.replace('-', '$-$', 1) if s.startswith('-') else s


def boxed(t):
    return '\\adjustbox{max width=\\textwidth}{%\n' + t + '}'


def panels(build, groups):
    out = [boxed(build(g)) for g in groups if g]
    return HEAD + '\n' + '\n\\par\\vspace{0.9em}\n'.join(out) + '\n'


def additive_table(cells):
    def build(dss):
        L = ['\\begin{tabular}{l' + 'rrrr' * len(dss) + '}', '\\toprule',
             'Read-out & ' + ' & '.join(f'\\multicolumn{{4}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
             ' '.join(f'\\cmidrule(lr){{{2+4*k}-{5+4*k}}}' for k in range(len(dss))),
             ' & ' + ' & '.join(['P@1', '$\\Delta$', 'AUC$_{\\mathrm{pool}}$', 'AP'] * len(dss)) + ' \\\\',
             '\\midrule']
        for m in ('attnmil', 'gated_attn'):
            for kind in ('attention', 'additive'):
                row = [f'{DISPLAY[m]}, {kind}']
                for d in dss:
                    c = cells.get((m, d))
                    if c is None:
                        row += ['--'] * 4
                        continue
                    ch = mean(c, 'ChanceP@1')
                    p = mean(c, 'InstP@1' if kind == 'attention' else 'AddP@1')
                    a = mean(c, 'InstAUCPooled' if kind == 'attention' else 'AddAUCPooled')
                    row += [fmt(p, 1, pct=True),
                            fmt(None if p is None else p - ch, 1, pct=True, sign=True),
                            fmt(a), fmt(mean(c, 'BagAveragePrecision')) if kind == 'attention' else '']
                L.append(' & '.join(row) + ' \\\\')
            if m == 'attnmil':
                L.append('\\midrule')
        L += ['\\bottomrule', '\\end{tabular}']
        return '\n'.join(L)
    return panels(build, [CLASSICAL, [d for d in VOC]])


def deletion_table(cells, extras_path):
    """Deletion test (R1 pt 7, R3 pt 1). For bags with >= 2 present labels:
    drop in logit l when l's top instance is removed (delta_l), mean drop of the
    other present labels (delta_l'), and the drop in logit l when a random other
    instance is removed instead (delta_l^rnd, all bags)."""
    ex = json.load(open(extras_path))['cells'] if os.path.exists(extras_path) else {}

    def build(dss):
        L = ['\\begin{tabular}{l' + 'rrr' * len(dss) + '}', '\\toprule',
             'Method & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
             ' '.join(f'\\cmidrule(lr){{{2+3*k}-{4+3*k}}}' for k in range(len(dss))),
             ' & ' + ' & '.join(['$\\delta_l$', "$\\delta_{l'}$", '$\\delta_l^{\\mathrm{rnd}}$'] * len(dss)) + ' \\\\',
             '\\midrule']
        for m in ORDER:
            row = [DISPLAY[m]]
            for d in dss:
                c, e = cells.get((m, d)), ex.get(f'{m}__{d}', {})
                row += (['--'] * 3 if c is None or 'del_self_present' not in e else
                        [fmt(e['del_self_present'], 2), fmt(e['del_other_present'], 2),
                         fmt(mean(c, 'DelRndSelf'), 2)])
            L.append(' & '.join(row) + ' \\\\')
            if m == 'transmil_lite':
                L.append('\\midrule')
        L += ['\\bottomrule', '\\end{tabular}']
        return '\n'.join(L)
    return panels(build, [CLASSICAL, VOC])


def hap_table(cells):
    dss = CLASSICAL
    L = [HEAD, '\\begin{tabular}{l' + 'rrr' * len(dss) + '}', '\\toprule',
         'HAP setting & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
         ' '.join(f'\\cmidrule(lr){{{2+3*k}-{4+3*k}}}' for k in range(len(dss))),
         ' & ' + ' & '.join(['$\\Delta$', 'AUC$_{\\mathrm{pool}}$', 'AP'] * len(dss)) + ' \\\\',
         '\\midrule']
    alpha = {}
    for key, name in HAP_ROWS:
        row = [name]
        for d in dss:
            c = cells.get((key, d))
            if c is None:
                row += ['--'] * 3
                continue
            row += [fmt(mean(c, 'InstP@1') - mean(c, 'ChanceP@1'), 1, pct=True, sign=True),
                    fmt(mean(c, 'InstAUCPooled')), fmt(mean(c, 'BagAveragePrecision'))]
            al = [a for r in c['instance_per_model'] for a in r.get('HapAlpha', [])]
            if al:
                alpha[f'{key}__{d}'] = {'mean': float(np.mean(al)), 'min': float(np.min(al)),
                                        'max': float(np.max(al)), 'sd': float(np.std(al))}
        L.append(' & '.join(row) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    return HEAD + '\n' + boxed('\n'.join(L[1:])) + '\n', alpha


def f1_table(cells):
    def build(dss):
        L = ['\\begin{tabular}{l' + 'rrr' * len(dss) + '}', '\\toprule',
             'Method & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
             ' '.join(f'\\cmidrule(lr){{{2+3*k}-{4+3*k}}}' for k in range(len(dss))),
             ' & ' + ' & '.join(['AP', 'Ma-F1', 'Mi-F1'] * len(dss)) + ' \\\\', '\\midrule']
        for m in ORDER:
            row = [DISPLAY[m]]
            for d in dss:
                c = cells.get((m, d))
                row += (['--'] * 3 if c is None else
                        [fmt(mean(c, 'BagAveragePrecision')), fmt(mean(c, 'BagMacroF1')),
                         fmt(mean(c, 'BagMicroF1'))])
            L.append(' & '.join(row) + ' \\\\')
            if m == 'transmil_lite':
                L.append('\\midrule')
        L += ['\\bottomrule', '\\end{tabular}']
        return '\n'.join(L)
    return panels(build, [CLASSICAL, VOC])


def misses_table(extras_path):
    """Non-partitioned benchmarks: where top-1 misses land, and multi-label bags."""
    if not os.path.exists(extras_path):
        return HEAD + '\n% extras not available\n'
    ex = json.load(open(extras_path))['cells']
    dss = ['hja_birdsong'] + VOC
    L = ['\\begin{tabular}{l' + 'rrr' * len(dss) + '}', '\\toprule',
         'Method & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
         ' '.join(f'\\cmidrule(lr){{{2+3*k}-{4+3*k}}}' for k in range(len(dss))),
         ' & ' + ' & '.join(['bg', 'P@1$_{\\ge2}$', ''] * len(dss)).replace(' &  &', ' &') + ' \\\\',
         '\\midrule']
    # columns per dataset: share of misses on background, multi-label-bag P@1
    L[1 + 3] = ' & ' + ' & '.join(['miss bg', 'P@1 ($\\ge 2$)', '$\\Delta$'] * len(dss)) + ' \\\\'
    refc, refg = ['\\textit{chance} ($\\ge 2$)'], ['\\textit{ceiling} ($\\ge 2$)']
    for m in ORDER:
        row = [DISPLAY[m]]
        for d in dss:
            c = ex.get(f'{m}__{d}')
            if c is None or 'ml_P@1' not in c:
                row += ['--'] * 3
                continue
            row += [fmt(c.get('frac_miss_background'), 0, pct=True) + '\\%',
                    fmt(c['ml_P@1'], 1, pct=True),
                    fmt(c['ml_P@1'] - c['ml_chance'], 1, pct=True, sign=True)]
        L.append(' & '.join(row) + ' \\\\')
        if m == 'transmil_lite':
            L.append('\\midrule')
    for d in dss:
        c = ex.get(f'attnmil__{d}')
        refc += ['', fmt(None if c is None else c['ml_chance'], 1, pct=True), '']
        refg += ['', fmt(None if c is None else c['ml_ceiling'], 1, pct=True), '']
    L += ['\\midrule', ' & '.join(refc) + ' \\\\', ' & '.join(refg) + ' \\\\',
          '\\bottomrule', '\\end{tabular}']
    return HEAD + '\n' + boxed('\n'.join(L)) + '\n'


def tau_table(extras_path):
    """VOC-Patch-Seg re-scored at three overlap thresholds (R1 pt 4a, R3 pt 2).
    Bag labels are image-level and do not depend on tau; only patch labels do."""
    if not os.path.exists(extras_path):
        return HEAD + '\n% extras not available\n'
    ex = json.load(open(extras_path))['cells']
    taus = (0.05, 0.25, 0.5)
    d = 'voc2012seg_nc'
    L = ['\\begin{tabular}{l' + 'rrr' * len(taus) + '}', '\\toprule',
         'Method & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{$\\tau = {t}$}}' for t in taus) + ' \\\\',
         ' '.join(f'\\cmidrule(lr){{{2+3*k}-{4+3*k}}}' for k in range(len(taus))),
         ' & ' + ' & '.join(['P@1', '$\\Delta$', 'AUC$_{\\mathrm{pool}}$'] * len(taus)) + ' \\\\',
         '\\midrule']
    for m in ORDER:
        c = ex.get(f'{m}__{d}')
        row = [DISPLAY[m]]
        for t in taus:
            if c is None or f'tau{t}_P@1' not in c:
                row += ['--'] * 3
                continue
            row += [fmt(c[f'tau{t}_P@1'], 1, pct=True),
                    fmt(c[f'tau{t}_P@1'] - c[f'tau{t}_chance'], 1, pct=True, sign=True),
                    fmt(c[f'tau{t}_aucpool'])]
        L.append(' & '.join(row) + ' \\\\')
        if m == 'transmil_lite':
            L.append('\\midrule')
    ref = ex.get(f'attnmil__{d}', {})
    L.append('\\midrule')
    for name, key in (('\\textit{chance}', 'chance'), ('\\textit{ceiling (agnostic)}', 'ceiling'),
                      ('\\textit{scorable pairs}', 'pairs')):
        row = [name]
        for t in taus:
            v = ref.get(f'tau{t}_{key}')
            row += ['', ('--' if v is None else (f'{v:.0f}' if key == 'pairs' else fmt(v, 1, pct=True))), '']
        L.append(' & '.join(row) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    return HEAD + '\n' + boxed('\n'.join(L)) + '\n'


def ensemble_table(cells):
    dss = CLASSICAL + VOC
    L = ['\\begin{tabular}{l' + 'rr' * len(dss) + '}', '\\toprule',
         'Method & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{DS[d]}}}' for d in dss) + ' \\\\',
         ' '.join(f'\\cmidrule(lr){{{2+2*k}-{3+2*k}}}' for k in range(len(dss))),
         ' & ' + ' & '.join(['model', 'ens.'] * len(dss)) + ' \\\\', '\\midrule']
    gaps = {}
    for m in ORDER:
        row = [DISPLAY[m]]
        for d in dss:
            c = cells.get((m, d))
            if c is None:
                row += ['--'] * 2
                continue
            pm = mean(c, 'BagAveragePrecision')
            en = c['bag_metrics_mean_std']['AveragePrecision'][0]
            row += [fmt(pm), fmt(en)]
            gaps[f'{m}__{d}'] = en - pm
        L.append(' & '.join(row) + ' \\\\')
        if m == 'transmil_lite':
            L.append('\\midrule')
    L += ['\\bottomrule', '\\end{tabular}']
    return HEAD + '\n' + boxed('\n'.join(L)) + '\n', gaps


def within_arch(cells):
    """Spearman(AP, P@1) across one cell's models, after centring both on their
    fold means: fold difficulty moves AP and P@1 together, so raw correlations
    over the 35 models mostly measure the folds. Cells whose P@1 is fixed by
    construction (label-agnostic on partitioned data) are skipped."""
    out = {}
    for (m, d), c in cells.items():
        R = c['instance_per_model']
        if any(r.get('BagAveragePrecision') is None for r in R) or len(R) < 8:
            continue
        folds = sorted({r['fold'] for r in R})
        ap = np.array([r['BagAveragePrecision'] for r in R], float)
        p1 = np.array([r['InstP@1'] for r in R], float)
        fi = np.array([r['fold'] for r in R])
        for f in folds:
            ap[fi == f] -= ap[fi == f].mean()
            p1[fi == f] -= p1[fi == f].mean()
        if np.std(p1) < 1e-12:
            continue
        rho, p = spearmanr(ap, p1)
        out[f'{m}__{d}'] = {'n_models': len(R), 'spearman_rho_fold_centred': float(rho),
                            'p': float(p)}
    return out


def main():
    global RESULTS
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default='paper_attribution/tables')
    ap.add_argument('--results', default=RESULTS)
    a = ap.parse_args()
    RESULTS = a.results
    os.makedirs(a.outdir, exist_ok=True)
    cells = load()
    w = lambda n, t: open(os.path.join(a.outdir, n), 'w').write(t)
    w('additive_readout.tex', additive_table(cells))
    w('deletion_test.tex', deletion_table(cells, os.path.join(a.outdir, 'attribution_extras.json')))
    t, alpha = hap_table(cells)
    w('hap_ablation.tex', t)
    w('bag_f1.tex', f1_table(cells))
    w('attribution_misses.tex', misses_table(os.path.join(a.outdir, 'attribution_extras.json')))
    w('tau_sweep.tex', tau_table(os.path.join(a.outdir, 'attribution_extras.json')))
    t, gaps = ensemble_table(cells)
    w('ensemble_ap.tex', t)
    summ = {'n_cells': len(cells), 'hap_alpha': alpha, 'ensemble_minus_model_ap': gaps,
            'within_architecture_spearman_ap_p1': within_arch(cells)}
    json.dump(summ, open(os.path.join(a.outdir, 'revision_summary.json'), 'w'), indent=1)
    g = np.array(list(gaps.values())) if gaps else np.array([0.0])
    print(f'{len(cells)} cells; ensemble - per-model AP: '
          f'{100*g.min():.1f}..{100*g.max():.1f} pts')


if __name__ == '__main__':
    main()
